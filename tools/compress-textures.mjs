#!/usr/bin/env node
// KTX2 / Basis Universal compression of the PBR texture sets fetched by fetch-textures.mjs, so they ship GPU-compressed
// (transcoded at load time to ASTC / BC7 / ETC2 by three's KTX2Loader; engine/src/render/TextureSets.js). For every
// set in <dir>/manifest.json it writes <out>/<id>/{diff,nor_gl,rough,ao}.ktx2 next to the JPGs and records them in the
// manifest (`ktx2: true`, `ktx2Maps: { Diffuse|nor_gl|Rough|AO: { file, bytes, codec, srcBytes, psnr, ... } }`). The
// JPGs stay: the loader falls back to them when a renderer has no compressed format, a .ktx2 is missing, or `?ktx2=0`.
//
//   node engine/tools/compress-textures.mjs --dir public/textures              (all sets; skips up-to-date files)
//   --sets red_bricks_04,stucco_b   (set ids or manifest roles)    --out <dir> (default: --dir)   --force   --dry-run
//   --quality 160 (ETC1S quality 1-255)   --effort 2 (ETC1S effort 0-6)   --uastc-level 2 (0-4)   --rdo 0 (UASTC RDO lambda)
//   --uastc diff,white_stucco,red_bricks_04/diff   promote maps / sets / set-maps to UASTC (default: normals only)
//   --etc1s nor_gl                                 demote to ETC1S (smallest files, visibly blocky normals)
//   --basis public/basis   copy three's basis_transcoder.{js,wasm} there (KTX2Loader.setTranscoderPath); --basis-only
//   export async function compressTextures(opts) / copyTranscoder(dest)
//
// Encoder: the official Basis Universal encoder compiled to WASM, from the `ktx2-encoder` npm package (MIT wrapper;
// Basis Universal is Apache-2.0, see node_modules/ktx2-encoder/THIRD_PARTY_NOTICES.md), driven through its low-level
// BasisEncoder API in worker threads; JPEG decode via `jpeg-js`, KTX2 key/values via `ktx-parse`. Install them with
// `npm i -D ktx2-encoder jpeg-js ktx-parse` (devDependencies of the game; only this tool needs them).
//
// Codecs per map (all with a full mip chain generated by the encoder with wrap addressing, since the sets tile):
//   Diffuse  ETC1S (BasisLZ supercompression), sRGB, mips filtered in sRGB    -> ~0.3-0.6x the JPG
//   nor_gl   UASTC LDR 4x4 + Zstandard, linear, normal-map preset, mip renormalisation (ETC1S normals are blocky)
//   Rough/AO ETC1S, linear
// Images are Y-flipped at encode time (KTXorientation "ru") so the compressed data matches what TextureLoader's
// flipY = true produces for the JPGs: same UVs, same orientation, no consumer changes.
import fsSync from 'node:fs';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import { runCli } from './cli.mjs';

/** CLI flags / compressTextures options. */
export const SPEC = {
  dir: { type: 'string', def: 'public/textures', help: 'texture root with manifest.json and <id>/*.jpg' },
  out: { type: 'string', help: 'output root for <id>/*.ktx2 + manifest.json (default: --dir)' },
  sets: { type: 'string', help: 'comma list of set ids or roles (default: every set in the manifest)' },
  quality: { type: 'number', def: 160, help: 'ETC1S quality 1-255 (codebook size: higher = larger, better)' },
  effort: { type: 'number', def: 2, help: 'ETC1S compression effort 0-6 (encode time, not quality)' },
  'uastc-level': { type: 'number', def: 2, help: 'UASTC pack level 0-4 (higher = slower, better)' },
  rdo: { type: 'number', def: 0, help: 'UASTC rate-distortion lambda (0 = off; 1-4 shrinks Zstd output, lowers quality)' },
  uastc: { type: 'string', help: 'maps / set ids / id/map to encode as UASTC (e.g. diff or white_stucco/diff)' },
  etc1s: { type: 'string', help: 'maps / set ids / id/map to encode as ETC1S (e.g. nor_gl)' },
  jobs: { type: 'number', def: Math.max(1, Math.min(8, os.cpus().length - 1)), help: 'parallel encoder workers' },
  basis: { type: 'string', help: "copy three's Basis transcoder here (default: <dir>/../basis; 'none' = skip)" },
  'basis-only': { type: 'bool', def: false, help: 'only copy the transcoder (no encoding, no encoder deps needed)' },
  force: { type: 'bool', def: false, help: 're-encode even when the .ktx2 is up to date' },
  'dry-run': { type: 'bool', def: false, help: 'print the plan only (no encoding, nothing written)' },
};

// manifest map key -> codec defaults. src/out names come from the manifest (maps[key]) with .jpg -> .ktx2.
export const MAP_CODECS = {
  Diffuse: { short: 'diff', codec: 'etc1s', srgb: true },
  nor_gl: { short: 'nor_gl', codec: 'uastc', normal: true },
  Rough: { short: 'rough', codec: 'etc1s' },
  AO: { short: 'ao', codec: 'etc1s' },
};
const WORKER_ROLE = 'ktx2-compress-worker';
const KB = (b) => (b / 1024).toFixed(0);
const MB = (b) => (b / 1048576).toFixed(2);

async function encoderDeps() {
  try {
    const [{ NodeBasisEncoder }, jpeg, ktx] = await Promise.all([import('ktx2-encoder'), import('jpeg-js'), import('ktx-parse')]);
    return { NodeBasisEncoder, jpeg: jpeg.default || jpeg, ktx };
  } catch (e) {
    throw new Error(`compress-textures needs the encoder packages: npm i -D ktx2-encoder jpeg-js ktx-parse (${e.message})`);
  }
}

// ------------------------------------------------------------------ worker: decode JPG, encode KTX2, measure PSNR
if (!isMainThread && workerData && workerData.role === WORKER_ROLE) {
  const deps = await encoderDeps();
  const B = await new deps.NodeBasisEncoder().init();
  const TF = B.basis_tex_format;
  parentPort.on('message', async (job) => {
    try { parentPort.postMessage({ id: job.id, ok: true, ...(await encodeOne(B, TF, deps, job)) }); } catch (e) { parentPort.postMessage({ id: job.id, ok: false, error: e.message || String(e) }); }
  });
  parentPort.postMessage({ ready: true });
}

async function encodeOne(B, TF, deps, job) {
  const t0 = performance.now();
  const img = deps.jpeg.decode(await fs.readFile(job.src), { useTArray: true, formatAsRGBA: true, maxMemoryUsageInMB: 1024 });
  const tDec = performance.now();
  const e = new B.BasisEncoder();
  let buf;
  try {
    e.setCreateKTX2File(true); e.setDebug(false); e.setStatusOutput(false); e.setPrintStats(false);
    e.setTexType(0); // 2D
    e.setFormatMode(job.codec === 'uastc' ? TF.cUASTC_LDR_4x4.value : TF.cETC1S.value);
    if (job.normal) e.setNormalMapPreset(); else if (job.srgb) e.setSRGBPreset(); else e.setLinearPreset();
    e.setSRGBOptions(!!job.srgb); // perceptual metric + sRGB mip filtering + sRGB transfer function in the DFD
    e.setMipGen(true); e.setMipWrapping(true); e.setMipSRGB(!!job.srgb); e.setMipRenormalize(!!job.normal);
    e.setYFlip(true); e.setCheckForAlpha(false); e.setForceAlpha(false);
    if (job.codec === 'uastc') {
      e.setPackUASTCFlags(job.uastcLevel); e.setKTX2UASTCSupercompression(true);
      if (job.rdo > 0) { e.setRDOUASTC(true); e.setRDOUASTCQualityScalar(job.rdo); }
    } else {
      e.setQualityLevel(job.quality); e.setETC1SCompressionLevel(job.effort);
    }
    if (e.setSliceSourceImage(0, img.data, img.width, img.height, 0 /* raw RGBA */) === false) throw new Error('setSliceSourceImage failed');
    const out = new Uint8Array(img.width * img.height * 8 + 65536);
    const n = e.encode(out);
    if (!n) throw new Error('encode failed');
    buf = out.slice(0, n);
  } finally { e.delete(); }
  const tEnc = performance.now();
  // orientation metadata: rows are stored bottom-up (Y-flipped), i.e. "ru"
  const c = deps.ktx.read(buf);
  c.keyValue.KTXorientation = 'ru';
  buf = deps.ktx.write(c, { keepWriter: true });
  // quality: transcode mip 0 back to RGBA32 and compare with the decoded JPG (rows flipped back)
  const k = new B.KTX2File(buf);
  let psnr = null, levels = 0;
  try {
    if (!k.isValid() || !k.startTranscoding()) throw new Error('written .ktx2 does not transcode');
    levels = k.getLevels();
    const dst = new Uint8Array(k.getImageTranscodedSizeInBytes(0, 0, 0, 13));
    if (!k.transcodeImage(dst, 0, 0, 0, 13 /* cTFRGBA32 */, 0, -1, -1)) throw new Error('transcode failed');
    const W = img.width, H = img.height, ch = job.normal ? 2 : job.srgb ? 3 : 1;
    let se = 0;
    for (let y = 0; y < H; y++) {
      const s = (H - 1 - y) * W * 4, d = y * W * 4;
      for (let x = 0; x < W * 4; x += 4) for (let q = 0; q < ch; q++) { const v = img.data[s + x + q] - dst[d + x + q]; se += v * v; }
    }
    const mse = se / (W * H * ch);
    psnr = mse > 0 ? +(10 * Math.log10((255 * 255) / mse)).toFixed(2) : 99;
  } finally { k.close(); k.delete(); }
  await fs.mkdir(path.dirname(job.out), { recursive: true });
  await fs.writeFile(job.out, buf);
  return { bytes: buf.length, width: img.width, height: img.height, levels, psnr, decodeMs: tDec - t0, encodeMs: tEnc - tDec, ms: performance.now() - t0 };
}

// ------------------------------------------------------------------ main thread
function runPool(jobs, n, onDone) {
  if (!jobs.length) return Promise.resolve([]);
  return new Promise((resolve, reject) => {
    const results = new Array(jobs.length), workers = [];
    let next = 0, done = 0, failed = null, settled = false;
    const finish = () => { if (settled) return; settled = true; for (const w of workers) w.terminate(); failed ? reject(failed) : resolve(results); };
    const feed = (w) => {
      if (failed) return;
      if (next >= jobs.length) { w.idle = true; if (workers.every((x) => x.idle)) finish(); return; }
      const i = next++; w.idle = false; w.postMessage({ ...jobs[i], id: i });
    };
    for (let k = 0; k < Math.min(n, jobs.length); k++) {
      const w = new Worker(new URL(import.meta.url), { workerData: { role: WORKER_ROLE } });
      workers.push(w);
      w.on('message', (m) => {
        if (m.ready) return feed(w);
        if (!m.ok) { failed = new Error(`${jobs[m.id].label}: ${m.error}`); return finish(); }
        results[m.id] = m; done++;
        onDone && onDone(jobs[m.id], m, done, jobs.length);
        feed(w);
      });
      w.on('error', (e) => { failed = failed || e; finish(); });
    }
  });
}

/** Copy three's basis_transcoder.{js,wasm} (the version KTX2Loader expects) to `dest`. Returns files copied. */
export async function copyTranscoder(dest) {
  const copied = [];
  await fs.mkdir(dest, { recursive: true });
  for (const f of ['basis_transcoder.js', 'basis_transcoder.wasm']) {
    const src = fileURLToPath(import.meta.resolve(`three/addons/libs/basis/${f}`));
    const dst = path.join(dest, f);
    const a = await fs.readFile(src);
    let same = false;
    try { same = (await fs.readFile(dst)).equals(a); } catch { /* missing */ }
    if (!same) { await fs.writeFile(dst, a); copied.push(f); }
  }
  return copied;
}

const tokens = (s) => String(s || '').split(',').map((x) => x.trim()).filter(Boolean);
function codecFor(id, key, o) {
  const d = MAP_CODECS[key], m = (list) => list.some((t) => t === d.short || t === key || t === id || t === `${id}/${d.short}` || t === `${id}/${key}`);
  if (m(o.uastcList)) return 'uastc';
  if (m(o.etc1sList)) return 'etc1s';
  return d.codec;
}
const paramsOf = (j) => (j.codec === 'uastc' ? `uastc l${j.uastcLevel}${j.rdo > 0 ? ` rdo${j.rdo}` : ''} zstd` : `etc1s q${j.quality} e${j.effort}`) + (j.srgb ? ' srgb' : ' linear') + (j.normal ? ' normal' : '') + ' mips yflip';

/** Compress the sets. opts: SPEC keys in camelCase. */
export async function compressTextures(opts = {}) {
  const d = (k) => (opts[k] !== undefined ? opts[k] : SPEC[k.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase())].def);
  const DIR = path.resolve(d('dir')), OUT = d('out') ? path.resolve(d('out')) : DIR;
  const basisOpt = d('basis'), BASIS = basisOpt === 'none' ? null : path.resolve(basisOpt || path.join(DIR, '..', 'basis'));
  if (opts.basisOnly) {
    if (!BASIS) return { basis: null };
    const c = await copyTranscoder(BASIS);
    console.log(`basis transcoder -> ${path.relative(process.cwd(), BASIS) || '.'} (${c.length ? `updated ${c.join(', ')}` : 'up to date'})`);
    return { basis: BASIS, copied: c };
  }
  const manifestPath = path.join(DIR, 'manifest.json');
  const manifest = JSON.parse(await fs.readFile(manifestPath, 'utf8'));
  const want = tokens(d('sets'));
  const o = {
    quality: Math.round(Math.min(255, Math.max(1, d('quality')))), effort: Math.round(Math.min(6, Math.max(0, d('effort')))),
    uastcLevel: Math.round(Math.min(4, Math.max(0, d('uastcLevel')))), rdo: Math.max(0, d('rdo')),
    uastcList: tokens(d('uastc')), etc1sList: tokens(d('etc1s')),
  };
  const entries = Object.entries(manifest.sets || {}).filter(([role, e]) => !want.length || want.includes(role) || want.includes(e.id));
  if (want.length && !entries.length) throw new Error(`--sets ${want.join(',')}: no matching set in ${manifestPath}`);
  const jobs = [], skipped = [];
  for (const [role, e] of entries) {
    for (const [key, src] of Object.entries(e.maps || {})) {
      const mc = MAP_CODECS[key];
      if (!mc || !/\.(jpe?g)$/i.test(src)) continue;
      const srcPath = path.join(DIR, e.id, src);
      let srcBytes;
      try { srcBytes = fsSync.statSync(srcPath).size; } catch { console.warn(`! ${e.id}/${src} missing, skipped`); continue; }
      const file = src.replace(/\.(jpe?g)$/i, '.ktx2');
      const j = { role, setId: e.id, key, label: `${e.id}/${file}`, src: srcPath, out: path.join(OUT, e.id, file), file, srcFile: src, srcBytes, codec: codecFor(e.id, key, o), srgb: !!mc.srgb, normal: !!mc.normal, ...o };
      j.params = paramsOf(j);
      const prev = e.ktx2Maps && e.ktx2Maps[key];
      let upToDate = false;
      if (!opts.force && prev && prev.params === j.params && prev.srcBytes === srcBytes && prev.file === file) {
        try { upToDate = fsSync.statSync(j.out).size === prev.bytes; } catch { upToDate = false; }
      }
      (upToDate ? skipped : jobs).push(j);
    }
  }
  console.log(`ktx2 plan: ${entries.length} sets, ${jobs.length} maps to encode, ${skipped.length} up to date -> ${path.relative(process.cwd(), OUT) || '.'} (ETC1S q${o.quality} e${o.effort}, UASTC l${o.uastcLevel}${o.rdo ? ` rdo ${o.rdo}` : ''}, ${d('jobs')} workers)`);
  if (opts.dryRun) {
    for (const j of jobs) console.log(`  ${j.label.padEnd(34)} ${j.params}`);
    console.log('  dry run: nothing encoded, nothing written');
    return { dryRun: true, jobs: jobs.length, skipped: skipped.length };
  }
  if (jobs.length) await encoderDeps(); // fail early with the install hint
  const t0 = performance.now();
  let cpu = 0;
  const results = await runPool(jobs, d('jobs'), (j, r, n, N) => {
    cpu += r.ms;
    console.log(`  [${String(n).padStart(3)}/${N}] ${j.label.padEnd(34)} ${j.codec.padEnd(5)} ${KB(j.srcBytes).padStart(5)} KB jpg -> ${KB(r.bytes).padStart(5)} KB ktx2  psnr ${String(r.psnr).padStart(5)} dB  ${(r.ms / 1000).toFixed(1)} s`);
  });
  const wall = performance.now() - t0;
  // manifest: per-set ktx2 flag + per-map entries (written to OUT; carries every other field through)
  const outManifest = OUT === DIR ? manifest : JSON.parse(JSON.stringify(manifest));
  jobs.forEach((j, i) => {
    const r = results[i], e = outManifest.sets[j.role];
    e.ktx2Maps = e.ktx2Maps || {};
    e.ktx2Maps[j.key] = { file: j.file, bytes: r.bytes, codec: j.codec, srgb: j.srgb, width: r.width, height: r.height, levels: r.levels, src: j.srcFile, srcBytes: j.srcBytes, psnr: r.psnr, params: j.params };
  });
  for (const [role] of entries) {
    const e = outManifest.sets[role];
    const all = Object.keys(e.maps || {}).filter((k) => MAP_CODECS[k]);
    e.ktx2 = all.length > 0 && all.every((k) => e.ktx2Maps && e.ktx2Maps[k]);
  }
  outManifest.ktx2 = { tool: 'engine/tools/compress-textures.mjs', encoder: 'Basis Universal (ktx2-encoder WASM)', orientation: 'ru', transcoder: 'basis/' };
  await fs.mkdir(OUT, { recursive: true });
  await fs.writeFile(path.join(OUT, 'manifest.json'), JSON.stringify(outManifest, null, 1));
  // summary: per map kind and total, over every compressed map of the selected sets
  const sums = {};
  for (const [role] of entries) {
    const e = outManifest.sets[role];
    for (const [key, m] of Object.entries(e.ktx2Maps || {})) {
      const s = sums[key] || (sums[key] = { n: 0, jpg: 0, ktx2: 0, psnr: 0 });
      s.n++; s.jpg += m.srcBytes; s.ktx2 += m.bytes; s.psnr += m.psnr || 0;
    }
  }
  let tj = 0, tk = 0;
  console.log('\nmap       codec  count   JPG MB  KTX2 MB  ratio  mean PSNR');
  for (const [key, s] of Object.entries(sums)) {
    tj += s.jpg; tk += s.ktx2;
    console.log(`${key.padEnd(9)} ${(MAP_CODECS[key] ? codecFor('', key, o) : '').padEnd(6)} ${String(s.n).padStart(5)} ${MB(s.jpg).padStart(8)} ${MB(s.ktx2).padStart(8)} ${(s.ktx2 / s.jpg).toFixed(2).padStart(6)} ${(s.psnr / s.n).toFixed(1).padStart(8)} dB`);
  }
  console.log(`${'total'.padEnd(16)} ${String(Object.values(sums).reduce((a, s) => a + s.n, 0)).padStart(5)} ${MB(tj).padStart(8)} ${MB(tk).padStart(8)} ${(tk / Math.max(1, tj)).toFixed(2).padStart(6)}`);
  console.log(`encoded ${jobs.length} maps in ${(wall / 1000).toFixed(1)} s wall (${(cpu / 1000).toFixed(1)} s CPU, ${d('jobs')} workers); ${skipped.length} up to date`);
  let copied = null;
  if (BASIS) {
    copied = await copyTranscoder(BASIS);
    console.log(`basis transcoder -> ${path.relative(process.cwd(), BASIS)} (${copied.length ? `updated ${copied.join(', ')}` : 'up to date'})`);
  }
  return { out: OUT, encoded: jobs.length, skipped: skipped.length, jpgBytes: tj, ktx2Bytes: tk, wallMs: wall, cpuMs: cpu, basis: BASIS, copied };
}

if (isMainThread) runCli(import.meta.url, 'engine/tools/compress-textures.mjs', 'KTX2 (Basis Universal) compression of the PBR texture sets', SPEC, compressTextures);
